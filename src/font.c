const uint8_t *font_chargen(void)
{
    static uint8_t rom[4096];
    static int built;
    if (!built) {
        memset(rom, 0, sizeof rom);
        for (size_t i = 0; i < sizeof glyphs / sizeof glyphs[0]; i++) {
            memcpy(rom + glyphs[i].code * 8, glyphs[i].rows, 8);
            for (int r = 0; r < 8; r++)                 /* reverse video at +128 */
                rom[(glyphs[i].code + 128) * 8 + r] = (uint8_t)~glyphs[i].rows[r];
        }
        for (int r = 0; r < 8; r++) rom[(32 + 128) * 8 + r] = 0xFF;
        memcpy(rom + 2048, rom, 2048);                 /* second (lower case) set */
        built = 1;
    }
    return rom;
}
